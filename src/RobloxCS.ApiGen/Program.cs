    private static HashSet<string> CollectClassNames(JsonElement root)
    {
        var set = new HashSet<string>();
        if (root.TryGetProperty("Classes", out var classes))
            foreach (var c in classes.EnumerateArray())
                if (c.TryGetProperty("Name", out var n))
                    set.Add(n.GetString()!);
        return set;
    }

    private static void EmitEnum(StringBuilder sb, JsonElement e)
    {
        var name = e.GetProperty("Name").GetString()!;
        sb.AppendLine($"public enum {Safe(name)} : long");
        sb.AppendLine("{");
        var seen = new HashSet<string>();
        if (e.TryGetProperty("Items", out var items))
            foreach (var item in items.EnumerateArray())
            {
                var itemName = item.GetProperty("Name").GetString()!;
                if (!IsIdentifier(itemName) || !seen.Add(itemName))
                    continue;
                sb.AppendLine($"    {Safe(itemName)} = {item.GetProperty("Value").GetInt64()},");
            }
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitClass(StringBuilder sb, JsonElement c, HashSet<string> known)
    {
        var name = c.GetProperty("Name").GetString()!;
        var super = c.TryGetProperty("Superclass", out var s) ? s.GetString() : null;
        var baseClause = super is not null && known.Contains(super) ? $" : {Safe(super)}" : "";

        sb.AppendLine($"public class {Safe(name)}{baseClause}");
        sb.AppendLine("{");

        // Constructor accessibility from the dump: creatable classes -> public (`new Part()` ->
        // Instance.new("Part")); NotCreatable/Service -> protected (blocks `new BasePart()`, still
        // callable as a base ctor by subclasses).
        var creatable = !HasTag(c, "NotCreatable") && !HasTag(c, "Service") && !HasTag(c, "Settings");
        sb.AppendLine($"    {(creatable ? "public" : "protected")} {Safe(name)}() {{ }}");

        var seen = new HashSet<string>();
        if (c.TryGetProperty("Members", out var members))
            foreach (var m in members.EnumerateArray())
                EmitMember(sb, m, known, seen, name);
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitMember(StringBuilder sb, JsonElement m, HashSet<string> known, HashSet<string> seen, string className)
    {
        var kind = m.GetProperty("MemberType").GetString();
        var name = m.GetProperty("Name").GetString()!;
        if (!seen.Add(kind + ":" + name)) // dedupe overloads/dupes (erasure-friendly)
            return;
        if (HasTag(m, "NotScriptable")) // truly unreachable from scripts ("Hidden" is still scriptable)
            return;
        if (!IsIdentifier(name) || name == className) // invalid C# ident, or member == enclosing type name
            return;

        switch (kind)
        {
            case "Property":
                sb.AppendLine($"    public {MapType(m.GetProperty("ValueType"), known)} {Safe(name)} {{ get; set; }} = default!;");
                break;
            case "Function":
                var ret = MapType(m.GetProperty("ReturnType"), known);
                var pars = BuildParams(m, known);
                sb.AppendLine($"    public {ret} {Safe(name)}({pars}) => default!;");
                break;
            case "Event":
                // Event -> a signal property. Single-parameter events are typed RBXScriptSignal<T>.
                var sig = "RBXScriptSignal";
                if (m.TryGetProperty("Parameters", out var eps) && eps.GetArrayLength() == 1)
                    sig = $"RBXScriptSignal<{MapType(eps[0].GetProperty("Type"), known)}>";
                sb.AppendLine($"    public {sig} {Safe(name)} {{ get; }} = default!;");
                break;
        }
    }

    private static string BuildParams(JsonElement m, HashSet<string> known)
    {
        if (!m.TryGetProperty("Parameters", out var ps))
            return "";
        var parts = new List<string>();
        var i = 0;
        foreach (var p in ps.EnumerateArray())
        {
            var pname = p.TryGetProperty("Name", out var pn) ? pn.GetString()! : $"arg{i}";
            parts.Add($"{MapType(p.GetProperty("Type"), known)} {Safe(pname)}");
            i++;
        }
        return string.Join(", ", parts);
    }

    // DataTypes the generator emits, derived from the DataTypes const (single source of truth).
    private static readonly HashSet<string> DataTypeNames =
        System.Text.RegularExpressions.Regex.Matches(DataTypes, @"public (?:struct|class) (\w+)")
            .Select(m => m.Groups[1].Value).ToHashSet();

    private static string MapType(JsonElement t, HashSet<string> known)
    {
        var name = t.TryGetProperty("Name", out var n) ? n.GetString()! : "object";
        var category = t.TryGetProperty("Category", out var c) ? c.GetString() : null;

        if (category == "Enum")
            return Safe(name);
        if (category == "Class" || known.Contains(name))
            return Safe(name) + "?";
        if (category == "DataType" && DataTypeNames.Contains(name))
            return name;

        return name switch
        {
            "string" or "Content" or "ProtectedString" => "string",
            "bool" => "bool",
            "int" => "int",
            "int64" => "long",
            "float" => "float", // Roblox float is 32-bit
            "double" => "double",
            "void" => "void",
            _ => "object",
        };
    }

    private static bool HasTag(JsonElement m, string tag) =>
        m.TryGetProperty("Tags", out var tags) && tags.ValueKind == JsonValueKind.Array
        && tags.EnumerateArray().Any(x => x.GetString() == tag);

    private static bool IsIdentifier(string s)
    {
        if (string.IsNullOrEmpty(s) || !(char.IsLetter(s[0]) || s[0] == '_'))
            return false;
        foreach (var ch in s)
            if (!char.IsLetterOrDigit(ch) && ch != '_')
                return false;
        return true;
    }

    // Escape C# keywords and invalid identifiers.
    private static string Safe(string id)
    {
        if (Keywords.Contains(id))
            return "@" + id;
        return id;
    }

    private static readonly HashSet<string> Keywords = new()
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
        "class", "const", "continue", "decimal", "default", "delegate", "do", "float", "else",
        "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
        "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
        "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
        "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual",
        "void", "volatile", "while",
    };
}

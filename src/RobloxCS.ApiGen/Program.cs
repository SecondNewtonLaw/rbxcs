namespace RobloxCS.ApiGen;

// Usage:
//   RobloxCS.ApiGen --fetch <out.cs>          fetch the live API dump from Roblox, then generate
//   RobloxCS.ApiGen <api-dump.json> <out.cs>  generate from a local dump file
// Emits C# declarations for the whole Roblox class hierarchy + enums + datatypes into `namespace Roblox`.
internal static class Program
{
    private static async Task<int> Main(string[] args)
    {
        string json, outPath;
        if (args.Length >= 2 && args[0] == "--fetch")
        {
            json = await FetchDumpAsync();
            outPath = args[1];
        }
        else if (args.Length >= 2)
        {
            json = File.ReadAllText(args[0]);
            outPath = args[1];
        }
        else
        {
            Console.Error.WriteLine("usage: RobloxCS.ApiGen (--fetch | <api-dump.json>) <out.cs>");
            return 1;
        }

        File.WriteAllText(outPath, Generate(json));
        Console.WriteLine($"rbxcs apigen: wrote {outPath}");
        return 0;
    }

    // Replicates Roblox-API-Dump-Tool: the current Studio deploy hash comes from versionQTStudio,
    // then the dump is fetched from the versioned CDN path.
    private static async Task<string> FetchDumpAsync()
    {
        using var http = new HttpClient();
        var version = (await http.GetStringAsync("https://setup.rbxcdn.com/versionQTStudio")).Trim();
        Console.Error.WriteLine($"rbxcs apigen: Roblox Studio {version}");
        return await http.GetStringAsync($"https://setup.rbxcdn.com/{version}-API-Dump.json");
    }

    public static string Generate(string json)
    {
        using var doc = JsonDocument.Parse(json);
        var root = doc.RootElement;
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> Roblox API surface generated from the API Dump.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Roblox;");
        sb.AppendLine();

        var known = CollectClassNames(root);
        var emitted = new HashSet<string>(DataTypeNames); // datatypes come from the const below

        if (root.TryGetProperty("Classes", out var classes))
            foreach (var c in classes.EnumerateArray())
            {
                var name = c.GetProperty("Name").GetString()!;
                if (emitted.Add(name))
                    EmitClass(sb, c, known);
            }

        if (root.TryGetProperty("Enums", out var enums))
            foreach (var e in enums.EnumerateArray())
            {
                var name = e.GetProperty("Name").GetString()!;
                if (emitted.Add(name))
                    EmitEnum(sb, e);
            }

        sb.Append(DataTypes);
        return sb.ToString();
    }

